/**

hbm_nway_test.cc -- N-way HBM contention fixture (hbm-bandwidth-contention).

Runs the static ET simulation (entry replicated from
congestion_aware/main.cc -- test-only duplicate, never part of the baseline
gates) over the synthetic 2-rank graph generated by
tests/make_hbm_nway_fixture.py, with a CompletionObserver hook capturing
every node's terminal tick. The fixture exercises the N-way equal-split
LocalHbmBandwidthModel end to end:

  rank 0: COMP(300B) + KV-restore(600B) + charged COMM_SEND(900B) -- the
          three-way equal-split scenario -- plus an uncharged
          (hbm-charge=false) 64B send that must NOT create an HBM job, and
          a calibrated COMP (duration_micros=5, 中-5 honor pin) that must
          bypass the model entirely;
  rank 1: COMP(300B) + KV-restore(600B) + charged COMM_RECV(900B) +
          MEM_STORE(1200B, hbm-access-mode=1 pool endpoint) -- the four-way
          split with both join flavors (network-side and port-side).

Assertions (local-mem-bw = 3000 GB/s = 3 B/ns, local-mem-latency = 100 ns;
all completions land on integer ticks, so equalities are exact):

  contention ON:
    - 3-way 1/3-rate numeric: rank0 COMP terminal == 400
      (100 latency + 300B / (3/3 B/ns)), RESTORE == 600 (2-way 1.5 B/ns
      tail), charged send == 700 (solo 3 B/ns tail; join with the faster
      network side);
    - 4-way on rank 1: COMP == 500, RESTORE == 800, RECV == 1000,
      MEM_STORE == 1100 (join of port@300 and HBM@1100 -> 1100);
    - 1/3-rate evidence: COMP(300B) completes exactly 300 ns after the
      latency under three concurrent streamers (full-rate would be 100 ns);
    - redistribution: after COMP completes at 400 the RESTORE rate doubles
      (300 remaining bytes served in 200 ns at 1.5 B/ns -> terminal 600);
    - hbm-charge=false: comm_read bytes == 900 exactly (the 64B pass-through
      send contributes nothing); its terminal is strictly after its issue
      (>= 800, network-only);
    - 中-5 honor pin: rank0 #4 calibrated COMP terminal == 5400（honor：不进
      流体模型；单 COMP 槽使其在 node0 后发射，终点=发射+5000）;
    - join fires exactly once: every (rank, node) terminal is recorded
      exactly once; total terminals == 9;
    - served bytes by category match the issued bytes;
    - peak concurrent jobs: 3 (rank0) / 4 (rank1); redistribution events:
      4 (rank0) / 6 (rank1).
  contention OFF (legacy A/B):
    - only COMP + restore share (50/50): COMP == 300, RESTORE == 400;
    - comm_read/comm_write/pool_read/pool_write served bytes == 0;
    - peak concurrent jobs == 2;
    - 中-5 honor pin: rank0 #4 calibrated COMP terminal == 5300（honor：不进
      流体模型；单 COMP 槽使其在 node0 后发射，终点=发射+5000）.

Build: the CMake target AstraSim_Analytical_Congestion_Aware_HbmNwayTest
(build with cmake --build build/astra_analytical/build_congestion_aware -j).
Run (from template/astra-sim-sh_3.0, after generating the fixture):
  python3 astra-sim/workload/execution_driven/tests/make_hbm_nway_fixture.py
  build/astra_analytical/build_congestion_aware/bin/\
AstraSim_Analytical_Congestion_Aware_HbmNwayTest \
    --workload-configuration=sh_test_mesh/generated/hbm_nway_fixture/fixture \
    --comm-group-configuration=sh_test_mesh/generated/hbm_nway_fixture/comm_group.json \
    --system-configuration=sh_test_mesh/generated/hbm_nway_fixture/system_on.json \
    --remote-memory-configuration=sh_test_mesh/generated/hbm_nway_fixture/remote_memory.json \
    --network-configuration=sh_test_mesh/generated/hbm_nway_fixture/network.yml \
    --logging-folder=off
  (then the same with system_off.json for the legacy A/B assertions)
Exit code 0 on ALL PASS.
*******************************************************************************/


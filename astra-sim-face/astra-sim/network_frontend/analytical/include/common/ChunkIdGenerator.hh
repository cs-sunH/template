#pragma once

#include "common/ChunkIdGeneratorEntry.hh"
#include <astra-network-analytical/common/Type.h>
#include <map>
#include <tuple>
#include <vector>

using namespace NetworkAnalytical;

namespace AstraSimAnalytical {

/**
 * ChunkIdGenerator generates unique chunk id for sim_send() and sim_recv()
 * calls given (tag, src, dest, chunk_size) tuple.
 */
class ChunkIdGenerator {
  public:
    /**
     * Constructor.
     */
    ChunkIdGenerator() noexcept;

    /**
     * Create unique chunk id for sim_send() call.
     *
     * @param tag tag of the sim_send() call
     * @param src src NPU ID of the sim_send() call
     * @param dest dest NPU ID of the sim_send() call
     * @param chunk_size chunk size of the sim_send() call
     * @return unique sim_send() chunk id
     */
    [[nodiscard]] int create_send_chunk_id(int tag,
                                           int src,
                                           int dest,
                                           ChunkSize chunk_size) noexcept;

    /**
     * Create unique chunk id for sim_recv call.
     *
     * @param tag tag of the sim_recv call
     * @param src src NPU ID of the sim_recv call
     * @param dest dest NPU ID of the sim_recv call
     * @param chunk_size chunk size of the sim_recv call
     * @return unique sim_recv chunk id
     */
    [[nodiscard]] int create_recv_chunk_id(int tag,
                                           int src,
                                           int dest,
                                           ChunkSize chunk_size) noexcept;

    /// Mark one callback-tracker entry as fully consumed. Each chunk id may
    /// complete exactly once per key generation: a duplicate completion, an
    /// unknown key, or an id never generated by sim_send() fails closed.
    /// A key is reclaimed only after every logical send under it has
    /// completed exactly once and both id streams have caught up, so legacy
    /// tag reuse and same-key concurrency remain valid and a stale callback
    /// can never alias an id reused by the next generation.
    void complete(int tag,
                  int src,
                  int dest,
                  ChunkSize chunk_size,
                  int chunk_id) noexcept;

    /// Diagnostic/test accessor: keys still needed for outstanding traffic.
    [[nodiscard]] size_t size() const noexcept;

    /// Run-end residual audit accessor: up to max_samples keys still resident
    /// in the map (recv-first keys intentionally wait for their sends, so a
    /// clean run recycles everything and any resident key at a quiescent run
    /// end is an anomaly worth reporting). Callers own the warn decision.
    /// Not noexcept: returns a freshly allocated vector.
    [[nodiscard]] std::vector<std::tuple<int, int, int, ChunkSize>>
    resident_key_samples(size_t max_samples) const;

  private:
    /// map from (tag, src, dest, chunk_size) tuple to ChunkIdGeneratorEntry
    std::map<std::tuple<int, int, int, ChunkSize>, ChunkIdGeneratorEntry>
        chunk_id_map;
};

}  // namespace AstraSimAnalytical

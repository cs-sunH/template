#include "common/ChunkIdGenerator.hh"
#include <algorithm>
#include <cassert>
#include <cstdio>
#include <cstdlib>

using namespace AstraSimAnalytical;

namespace {

[[noreturn]] void fail_chunk_lifecycle(const char* reason,
                                       const int tag,
                                       const int src,
                                       const int dest,
                                       const ChunkSize chunk_size,
                                       const int chunk_id) noexcept {
    std::fprintf(stderr,
                 "[Error] (network/analytical) ChunkIdGenerator completion "
                 "invariant failed: %s (tag=%d src=%d dest=%d size=%llu "
                 "chunk=%d)\n",
                 reason, tag, src, dest,
                 static_cast<unsigned long long>(chunk_size), chunk_id);
    std::abort();
}

}  // namespace

ChunkIdGenerator::ChunkIdGenerator() noexcept {
    chunk_id_map = {};
}

int ChunkIdGenerator::create_send_chunk_id(
    const int tag,
    const int src,
    const int dest,
    const ChunkSize chunk_size) noexcept {
    assert(tag >= 0);
    assert(src >= 0);
    assert(dest >= 0);
    assert(chunk_size > 0);

    // create key
    const auto key = std::make_tuple(tag, src, dest, chunk_size);

    // search whether the key exists
    auto entry = chunk_id_map.find(key);

    // if key doesn't exist, create new entry
    if (entry == chunk_id_map.end()) {
        entry = chunk_id_map.emplace(key, ChunkIdGeneratorEntry()).first;
    }

    // increment id and return
    entry->second.increment_send_id();
    entry->second.increment_outstanding();
    return entry->second.get_send_id();
}

int ChunkIdGenerator::create_recv_chunk_id(
    const int tag,
    const int src,
    const int dest,
    const ChunkSize chunk_size) noexcept {
    assert(tag >= 0);
    assert(src >= 0);
    assert(dest >= 0);
    assert(chunk_size > 0);

    // create key
    const auto key = std::make_tuple(tag, src, dest, chunk_size);

    // search whether the key exists
    auto entry = chunk_id_map.find(key);

    // key doesn't exist, create new entry
    if (entry == chunk_id_map.end()) {
        entry = chunk_id_map.emplace(key, ChunkIdGeneratorEntry()).first;
    }

    // increment recv id and return
    entry->second.increment_recv_id();
    return entry->second.get_recv_id();
}

void ChunkIdGenerator::complete(const int tag,
                                const int src,
                                const int dest,
                                const ChunkSize chunk_size,
                                const int chunk_id) noexcept {
    const auto key = std::make_tuple(tag, src, dest, chunk_size);
    const auto entry = chunk_id_map.find(key);
    if (entry == chunk_id_map.end()) {
        fail_chunk_lifecycle("unknown key", tag, src, dest, chunk_size,
                             chunk_id);
    }

    auto& state = entry->second;
    if (chunk_id < 0 || state.outstanding() == 0) {
        fail_chunk_lifecycle("duplicate completion or no outstanding send", tag,
                             src, dest, chunk_size, chunk_id);
    }
    // Per-chunk-id dedup: the same id must complete exactly once per
    // generation. Without this, a repeated completion for one id silently
    // consumes another in-flight send's outstanding credit whenever any
    // sibling send under the key is still in flight.
    if (!state.mark_chunk_completed(chunk_id)) {
        fail_chunk_lifecycle("duplicate completion for an already completed "
                             "chunk id",
                             tag, src, dest, chunk_size, chunk_id);
    }
    if (state.get_send_id() < chunk_id) {
        fail_chunk_lifecycle("chunk id was not generated by sim_send", tag,
                             src, dest, chunk_size, chunk_id);
    }

    state.decrement_outstanding();
    // Recycle gate (reclaim-period validation): the key is erased only when
    // the completed state is provably total -- every logical send accounted
    // (outstanding == 0), both id streams caught up (recv_id == send_id,
    // i.e. no recv-first call is still waiting for its send), and the dedup
    // set covering every generated id [0, send_id] exactly once. Under those
    // facts no CallbackTracker entry of this key can remain pending and no
    // chunk-arrival event is in flight, so a stale callback can never alias
    // a chunk id reused by the next generation: it would hit the tracker's
    // missing-entry abort instead. Extra recv calls beyond the send stream
    // (recv-first) keep the key resident until their sends arrive -- that
    // retention is what makes positional id pairing safe.
    if (state.outstanding() == 0 &&
        state.get_send_id() == state.get_recv_id() &&
        state.completed_count() ==
            static_cast<size_t>(state.get_send_id()) + 1) {
        chunk_id_map.erase(entry);
    }
}

size_t ChunkIdGenerator::size() const noexcept {
    return chunk_id_map.size();
}

std::vector<std::tuple<int, int, int, ChunkSize>>
ChunkIdGenerator::resident_key_samples(const size_t max_samples) const {
    std::vector<std::tuple<int, int, int, ChunkSize>> samples;
    samples.reserve(std::min(max_samples, chunk_id_map.size()));
    for (const auto& entry : chunk_id_map) {
        if (samples.size() >= max_samples) {
            break;
        }
        samples.push_back(entry.first);
    }
    return samples;
}

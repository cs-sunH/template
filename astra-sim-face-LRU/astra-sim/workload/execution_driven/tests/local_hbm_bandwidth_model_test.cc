/*
local_hbm_bandwidth_model_test.cc -- multi-user local-HBM bandwidth
contention fixture (hbm-bandwidth-contention).

Runs the static ET simulation (entry replicated from the step-1-3
completion fixture -- test-only duplicate, never part of the baseline
gates) over the synthetic 2-rank graph generated by
tests/make_local_hbm_fixture_et.py, in two network scenarios:

  fast  link 100 GB/s: the network side of every p2p transfer finishes
        long before the endpoint HBM job (network-first join order);
  slow  link 0.5 GB/s: the endpoint HBM job finishes long before the
        network side (HBM-first join order).

Numeric model under test (local-mem-bw 6 GB/s = 6 B/ns, latency 100 ns):

  rank 0 HBM users, all issued at tick 0:
    COMP       tensor_size 30 B   (roofline traffic, read+write merged)
    COMM_READ  60 B              (send endpoint of the 60 B transfer)
    COMM_WRITE 120 B             (recv endpoint of the 120 B transfer)
  Equal split of the single 6 B/ns scalar among N users:
    [100,115)  3 users @ 6/3 = 2 B/ns each -> COMP (30 B) drains in 15 ns
               -> completes at 115 (each of the three users really received
               exactly 1/3 of the rate);
    [115,125)  2 users @ 6/2 = 3 B/ns  -> COMM_READ (30 B left) drains in
               10 ns -> completes at 125 (the two survivors each received
               exactly 1/2 after the first completion);
    [125,135)  1 user  @ 6 B/ns         -> COMM_WRITE (60 B left) drains
               in 10 ns -> completes at 135.

  rank 1 HBM users: COMM_WRITE 60 B + COMM_READ 120 B (2-user case):
    [100,120)  2 users @ 3 B/ns -> WRITE completes at 120;
    [120,130)  1 user  @ 6 B/ns -> READ completes at 130.

  Node completion = join(network callback, endpoint HBM job), fired
  exactly once per node; the ranks' 4th/3rd nodes carry hbm-charge=false
  and complete on the network event alone (they also wait for the static
  single comm slot).  Fast-network joins complete at the HBM ticks above;
  slow-network joins complete at the network ticks.  The fluid drain rate
  of a yml "GB/s" link is bandwidth * 2^30 / 1e9 B/ns (NetworkFunction
  convention, 1 GB = 2^30 B): the 0.5 link drains at 0.536870912 B/ns, so
  60 B takes ceil(111.76)=112 ns, 120 B takes ceil(223.52)=224 ns and
  40 B takes ceil(74.51)=75 ns, each +20 ns propagation latency.

Expected completions (tick == exact value, and each (rank, node) fires
exactly once):
  fast: rank0 {1:115, 2:125, 3:135, 4:146}, rank1 {1:130, 2:120, 3:146}
  slow: rank0 {1:115, 2:132, 3:244, 4:227}, rank1 {1:244, 2:132, 3:227}
  (slow rank0 node 4 issues at 132, when the joined send frees the comm
  slot: 132 + 75 + 20 = 227)

Model side-band counters (identical in both scenarios; the HBM side does
not depend on the network):
  rank0 busy 35 ns, comp 30, comm_read 60, comm_write 120 served bytes,
        peak concurrency 3, redistribution events 4
  rank1 busy 30 ns, comm_read 120, comm_write 60, peak 2, events 2

Build: cmake --build build/astra_analytical/build_congestion_aware --target
       AstraSim_Analytical_Congestion_Aware_LocalHbmTest -j
Run (from template/astra-sim-face, after generating the fixture):
  python3 astra-sim/workload/execution_driven/tests/make_local_hbm_fixture_et.py
  build/astra_analytical/build_congestion_aware/AstraSim_Analytical/\
      AstraSim_Analytical_Congestion_Aware_LocalHbmTest --scenario fast
  (same binary with --scenario slow / --scenario legacy; the system and
  network configurations default to the fixture set)
Exit code 0 on ALL PASS.
*/

